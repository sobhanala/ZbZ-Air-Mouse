        touchpadStrokeColor = resources.getColor(R.color.touchpad_stroke, null);
        madgwickBeta = resources.getInteger(R.integer.madgwick_beta_milli) / 1000f;
        motionGainPercent = resources.getInteger(R.integer.motion_gain_percent);
        clickTwistThresholdDeg = resources.getInteger(R.integer.click_twist_threshold_deg);
